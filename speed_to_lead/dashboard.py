"""Static, anonymised HTML dashboard (aggregates only). Safe to publish on GitHub Pages."""

from __future__ import annotations

from html import escape
from typing import Any


def _fmt(v: Any, unit: str = "") -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:,.1f}{unit}"
    if isinstance(v, int):
        return f"{v:,}{unit}"
    return escape(str(v)) + unit


def _bar(v: float, vmax: float) -> str:
    w = 0 if vmax <= 0 else max(1, round(100 * v / vmax))
    return f'<span class="bar" style="width:{w}%"></span>'


def render(m: dict[str, Any], status: str, generated_at: str) -> str:
    syn = bool(m.get("synthetic"))
    banner = (
        '<div class="syn">SYNTHETIC DEMO DATA — generated by <code>make demo</code> with a fake WhatsApp '
        "server. Not real customers, not real results.</div>"
        if syn
        else ""
    )
    auto, human = m["auto_first_response_sec"], m["human_first_response_min"]
    src_rows = m["by_source"]
    vmax = max([b["leads"] for b in src_rows.values()] or [0])
    rmax = max([b["revenue"] for b in src_rows.values()] or [0])
    srcs = (
        "".join(
            f"<tr><td>{escape(k)}</td><td>{b['leads']}</td><td>{_bar(b['leads'], vmax)}</td><td>{b['contacted']}</td>"
            f"<td>{b['quoted']}</td><td>{b['won']}</td><td>₹{b['revenue']:,}</td><td>{_bar(b['revenue'], rmax)}</td></tr>"
            for k, b in src_rows.items()
        )
        or '<tr><td colspan="8">No leads yet.</td></tr>'
    )
    f = m["funnel"]
    fmax = max(f["leads"], 1)
    funnel = "".join(
        f"<tr><td>{label}</td><td>{f[k]}</td><td>{_bar(f[k], fmax)}</td></tr>"
        for k, label in (
            ("leads", "Leads"),
            ("contacted", "Human contacted"),
            ("quoted", "Quotation sent"),
            ("won", "Won (invoiced)"),
        )
    )
    ba = m["before_after"]

    def col(d: dict[str, Any]) -> list[str]:
        h = d["human_first_response_min"]
        return [
            _fmt(d["leads"]),
            _fmt(h["median"], " min"),
            _fmt(h["p90"], " min"),
            _fmt(d["pct_human_within_5min"], "%"),
            _fmt(d["conversion_pct"], "%"),
            "₹" + _fmt(d["revenue"]),
        ]

    labels = [
        "Leads",
        "First human reply — median",
        "First human reply — p90",
        "Replied within 5 min",
        "Lead → sale conversion",
        "Revenue (won)",
    ]
    b, live = col(ba["baseline"]), col(ba["live"])
    cmp_rows = "".join(
        f"<tr><td>{lab}</td><td>{x}</td><td>{y}</td></tr>" for lab, x, y in zip(labels, b, live, strict=True)
    )
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Speed-to-lead dashboard — paint shop, Pune</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:900px;margin:2rem auto;padding:0 1rem;color:#1d2433}}
h1{{font-size:1.4rem}} h2{{font-size:1.1rem;margin-top:2rem}}
.status{{background:#eef4ff;border-left:4px solid #3a6ff7;padding:.6rem 1rem}}
.syn{{background:#fff3cd;border:2px solid #d39e00;padding:.6rem 1rem;font-weight:600;margin-bottom:1rem}}
.kpis{{display:grid;grid-template-columns:repeat(auto-fit,minmax(180px,1fr));gap:.8rem}}
.kpi{{border:1px solid #dde3ee;border-radius:8px;padding:.8rem}} .kpi b{{font-size:1.5rem;display:block}}
table{{border-collapse:collapse;width:100%;font-size:.9rem}} td,th{{border-bottom:1px solid #eee;padding:.35rem;text-align:left}}
.bar{{display:inline-block;height:.7rem;background:#3a6ff7;border-radius:3px}} small{{color:#667}}
</style></head><body>
{banner}
<h1>Speed-to-lead — United Trader (paint retail, Undri, Pune)</h1>
<p class="status">{escape(status)}</p>
<div class="kpis">
<div class="kpi"><b>{_fmt(m["leads_total"])}</b>leads</div>
<div class="kpi"><b>{_fmt(m["pct_auto_within_60s"], "%")}</b>WhatsApp leads auto-answered ≤60 s</div>
<div class="kpi"><b>{_fmt(auto["median"], " s")}</b>auto first response, median (p90 {_fmt(auto["p90"], " s")})</div>
<div class="kpi"><b>{_fmt(human["median"], " min")}</b>human first response, median (p90 {_fmt(human["p90"], " min")})</div>
<div class="kpi"><b>{_fmt(m["pct_human_within_5min"], "%")}</b>human reply ≤5 min (shop hours)</div>
</div>
<h2>Before / after</h2>
<p><small>Baseline = 2 weeks of the old manual process logged by the shop before go-live
({_fmt(ba["baseline"]["days_logged"])} days logged, {_fmt(ba["baseline"]["never_replied"])} enquiries never
replied). Times count from shop-open time.</small></p>
<table><tr><th></th><th>Baseline (manual)</th><th>Live (system)</th></tr>{cmp_rows}</table>
<h2>Funnel</h2><table>{funnel}</table>
<h2>By source</h2>
<table><tr><th>Source</th><th>Leads</th><th></th><th>Contacted</th><th>Quoted</th><th>Won</th><th>Revenue</th><th></th></tr>
{srcs}</table>
<p><small>Anonymised aggregates only — no names or phone numbers. Generated {escape(generated_at)}.
Source code: speed-to-lead repository.</small></p>
</body></html>
"""
